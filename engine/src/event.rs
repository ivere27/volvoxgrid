/// FIFO event queue that collects engine-generated events for delivery
/// to the platform layer (Android, Flutter, Web, etc.).
#[derive(Clone, Debug)]
pub struct QueuedGridEvent {
    pub event_id: i64,
    pub data: GridEventData,
}

impl GridEventData {
    pub fn heap_size_bytes(&self) -> usize {
        match self {
            GridEventData::AfterEdit {
                old_text, new_text, ..
            } => old_text.capacity() + new_text.capacity(),
            GridEventData::CellEditValidate { edit_text, .. } => edit_text.capacity(),
            GridEventData::CellEditChange { text } => text.capacity(),
            GridEventData::EditorListItemsRequest {
                data_source_id,
                filter_text,
                ..
            } => data_source_id.capacity() + filter_text.capacity(),
            GridEventData::CellChanged {
                old_text, new_text, ..
            } => old_text.capacity() + new_text.capacity(),
            GridEventData::ScrollTooltip { text } => text.capacity(),
            GridEventData::CustomRenderCell { text, .. } => text.capacity(),
            GridEventData::TypeAheadStarted { text, .. } => text.capacity(),
            GridEventData::FilterData { text, .. } => text.capacity(),
            GridEventData::Error { message, .. } => message.capacity(),
            GridEventData::TreeChildrenRequested { node_id, .. }
            | GridEventData::BeforeTreeNodeToggle { node_id, .. }
            | GridEventData::AfterTreeNodeToggle { node_id, .. }
            | GridEventData::TreeNodeActivate { node_id, .. }
            | GridEventData::TreeNodeContextMenu { node_id, .. } => node_id.capacity(),
            GridEventData::EnterCell { target, .. }
            | GridEventData::LeaveCell { target, .. }
            | GridEventData::BeforeMouseDown { target, .. }
            | GridEventData::MouseMove { target, .. }
            | GridEventData::Click { target, .. }
            | GridEventData::DblClick { target, .. } => target.heap_size_bytes(),
            _ => 0,
        }
    }
}

impl QueuedGridEvent {
    pub fn heap_size_bytes(&self) -> usize {
        self.data.heap_size_bytes()
    }
}

/// FIFO event queue that collects engine-generated events for delivery
/// to the platform layer (Android, Flutter, Web, etc.).
pub struct EventQueue {
    queue: VecDeque<QueuedGridEvent>,
}

impl EventQueue {
    pub fn new() -> Self {
        Self {
            queue: VecDeque::new(),
        }
    }

    pub fn heap_size_bytes(&self) -> usize {
        let mut bytes = self.queue.capacity() * std::mem::size_of::<QueuedGridEvent>();
        for event in &self.queue {
            bytes += event.heap_size_bytes();
        }
        bytes
    }

    /// Push an event onto the back of the queue.
    pub fn push(&mut self, event: GridEventData) {
        if let GridEventData::LeaveCell { row, col, target } = &event {
            // Drop a transient data-cell hover that entered and left before delivery.
            let cancels_pending_enter = self.queue.back().is_some_and(|back| {
                target.kind == pb::GridTargetKind::GridTargetDataCell as i32
                    && back.event_id == 0
                    && matches!(
                        &back.data,
                        GridEventData::EnterCell {
                            row: enter_row,
                            col: enter_col,
                            target: enter_target,
                        } if enter_row == row && enter_col == col && enter_target == target
                    )
            });
            if cancels_pending_enter {
                self.queue.pop_back();
                return;
            }
        }
        if matches!(event, GridEventData::MouseMove { .. }) {
            if let Some(back) = self.queue.back_mut() {
                if back.event_id == 0 && matches!(back.data, GridEventData::MouseMove { .. }) {
                    back.data = event;
                    return;
                }
            }
        }
        self.push_with_id(0, event);
    }

    /// Push an event with an optional correlation id.
    ///
    /// `event_id = 0` means "no correlation id".
    pub fn push_with_id(&mut self, event_id: i64, event: GridEventData) {
        self.queue.push_back(QueuedGridEvent {
            event_id,
            data: event,
        });
    }

    /// Pop the next event from the front of the queue, or `None` if empty.
    pub fn pop(&mut self) -> Option<QueuedGridEvent> {
        self.queue.pop_front()
    }

    /// Inspect the next event without removing it from the queue.
    pub fn peek(&self) -> Option<&QueuedGridEvent> {
        self.queue.front()
    }

    /// Drain all pending events into a `Vec`, leaving the queue empty.
    pub fn drain(&mut self) -> Vec<QueuedGridEvent> {
        self.queue.drain(..).collect()
    }

    /// Returns `true` if there are no pending events.
    pub fn is_empty(&self) -> bool {
        self.queue.is_empty()
    }

    /// Returns the number of pending events.
    pub fn len(&self) -> usize {
        self.queue.len()
    }
}

impl Default for EventQueue {
    fn default() -> Self {
        Self::new()
    }
}
