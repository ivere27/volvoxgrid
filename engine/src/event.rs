use std::collections::VecDeque;

use crate::proto::volvoxgrid::v1 as pb;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EventTarget {
    pub kind: i32,
    pub band: i32,
    pub slot_index: i32,
    pub slot_kind: i32,
    pub sub_mode: i32,
    pub custom_key: String,
    pub text: String,
    pub int_value: i64,
    pub status_flags: u32,
    pub data: Vec<u8>,
}

impl EventTarget {
    pub fn data_cell() -> Self {
        Self {
            kind: pb::GridTargetKind::GridTargetDataCell as i32,
            ..Self::default()
        }
    }

    pub fn background() -> Self {
        Self {
            kind: pb::GridTargetKind::GridTargetBackground as i32,
            ..Self::default()
        }
    }

    pub fn to_proto(&self) -> pb::GridEventTarget {
        pb::GridEventTarget {
            kind: self.kind,
            band: self.band,
            slot_index: self.slot_index,
            slot_kind: self.slot_kind,
            custom_key: self.custom_key.clone(),
            text: self.text.clone(),
            int_value: self.int_value,
            status_flags: self.status_flags,
            data: self.data.clone(),
            sub_mode: self.sub_mode,
        }
    }

    pub fn heap_size_bytes(&self) -> usize {
        self.custom_key.capacity() + self.text.capacity() + self.data.capacity()
    }
}

impl Default for EventTarget {
    fn default() -> Self {
        Self {
            kind: pb::GridTargetKind::GridTargetUnspecified as i32,
            band: pb::IndicatorBand::Unspecified as i32,
            slot_index: -1,
            slot_kind: 0,
            sub_mode: 0,
            custom_key: String::new(),
            text: String::new(),
            int_value: 0,
            status_flags: 0,
            data: Vec::new(),
        }
    }
}

